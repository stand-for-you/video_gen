import React from 'react';
import { Form, Mass, Crease, Patch, sp, sym, mix, dark, lite, ribbon, P, RED } from './Paint';
import type { Spec } from './Faces';
// ===== SCROLL KAOS PAINTED HAIR. Same face coordinates (skull top -236). A dark mass + separate painted locks (clumps),
// each lock with its own sheen and gap, global light from the head shape (hull) so the rim light only hits the outer edge.

const hc = (s: Spec) => (s.grey ? '#b9b7b0' : s.hair);
const lum = (c: string) => parseInt(c.slice(1, 3), 16) + parseInt(c.slice(3, 5), 16) + parseInt(c.slice(5, 7), 16);
const sheenOf = (c: string) => (lum(c) < 200 ? mix(c, '#8a96b8', 0.42) : lite(c, 0.4));
type Lock = { s: P[]; w: number; w1?: number };
const normal = (pts: P[]) => { const a = pts[0], b = pts[pts.length - 1]; let nx = -(b[1] - a[1]), ny = b[0] - a[0]; const m = Math.hypot(nx, ny) || 1; nx /= m; ny /= m; if (nx < 0) { nx = -nx; ny = -ny; } return [nx, ny]; };
const shift = (pts: P[], dx: number, dy: number, t0 = 0.1, t1 = 0.85): P[] => { const n = pts.length; return pts.filter((_, i) => i / (n - 1) >= t0 && i / (n - 1) <= t1 || n < 4).map((p) => [p[0] + dx, p[1] + dy]); };

// mass + locks painted as one volume; each lock adds a dark gap on its shadow edge and a sheen stroke on its lit edge
const HairMass: React.FC<{ id: string; c: string; S: Sty; gloss?: number }> = ({ id, c, S, gloss = 1 }) => {
  const gap = dark(c, lum(c) < 200 ? 0.6 : 0.32), sh = sheenOf(c);
  const ribs = S.locks.map((k) => ribbon(k.s, k.w, k.w1 || 0, 10));
  return (
    <Mass id={id} ds={[S.mass, ...ribs]} c={c} hull={S.hull} so={84} lo={70} ro={16} soft={24} line={mix(gap, '#000', 0.3)} lineO={0.6}>
      <Patch d={S.mass} c={dark(c, 0.25)} o={0.35} b={12} />
      <Patch d="M-150,-262 C-60,-318 80,-318 170,-250 C120,-226 -40,-238 -150,-234Z" c={sh} o={0.45 * gloss} b={24} />
      {S.locks.map((k, i) => { const [nx, ny] = normal(k.s); return (
        <g key={i}>
          <Crease d={sp(shift(k.s, nx * k.w * 0.34, ny * k.w * 0.34, 0, 0.95), false)} c={gap} w={Math.max(5, k.w * 0.22)} o={0.75} b={3} />
          <Crease d={sp(shift(k.s, -nx * k.w * 0.1, -ny * k.w * 0.1, 0.08, 0.62), false)} c={sh} w={Math.max(4, k.w * 0.16)} o={0.75 * gloss} b={3} />
          <Crease d={sp(shift(k.s, -nx * k.w * 0.28, -ny * k.w * 0.28, 0.15, 0.5), false)} c={lite(sh, 0.2)} w={3} o={0.4 * gloss} b={3} />
        </g>); })}
    </Mass>
  );
};

